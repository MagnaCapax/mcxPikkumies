<?php
/**
 * HermesUserConfig: the only code that changes the user's Hermes files (local/hermes/config.yaml and .env) once
 * they exist (ADR-0062). Each change is backed up first and logged (HermesConfigBackup).
 * - seed: no config.yaml yet: written once, with every setting.
 * - migrate: once, from the layout where every start rewrote both files. The old "this file is rewritten" line 1 is
 *   replaced, Pikkumies' own PIKKUMIES_API_KEY line leaves .env (the key is in the managed .env now), and hidden
 *   shipped skills leave Hermes' skills.disabled (they are no longer generated). Every other byte stays. The marker
 *   (local/state/hermes-config.json) is written last; the old line 1 seen again (an older version ran) runs it again.
 * - skills dir: the generated skills directory goes back into skills.external_dirs when it is missing.
 * - telemetry answer: Hermes' shared-metrics "No thanks" goes back in when it is gone (HermesTelemetry, ADR-0072).
 * - skin: once per install, display.skin gets the Pikkumies skin when the file names no skin (StatusTheme, ADR-0061).
 * - browser: once per install, browser.restrict_evaluate becomes true when the file does not name it (ADR-0077).
 * The edits of single keys go through Hermes' own `config get/set`, which keeps every other entry and the file's comments, so
 * they wait until Hermes is built. A failed edit is logged and noted on stderr, the start goes on (the pins and hooks
 * are in the managed file), and the next start tries again. Hermes keeps copies too (HERMES_HOME/backups/config/).
 */
require_once __DIR__ . '/HermesConfigBackup.php';
require_once __DIR__ . '/HermesTelemetry.php';
require_once __DIR__ . '/StatusTheme.php';

class HermesUserConfig
{
    const OLD_HEAD = '# Generated by pikkumies.';
    const OLD_TAIL = 'this file is rewritten.';

    /** Test seam: the hermes command ('' = not built; null = HermesInstall::bin()). */
    public static $bin = null;

    /** At every start, after the managed files are written. $hidden: shipped skill names the user hid. */
    public static function apply($home, $seed, $skillDir, array $hidden)
    {
        $local = dirname($home);
        $cfg = "$home/config.yaml";
        $offer = HermesTelemetry::offerVersion();
        if (!self::migrationDue($cfg) && is_file($cfg) && self::hasSkillDir($cfg, $skillDir) && HermesTelemetry::isOff($cfg, $offer) && is_file(self::skinMarker($local)) && is_file(self::browseMarker($local))) {
            return; // the usual start: no lock, no Hermes process
        }
        @mkdir("$local/state", 0700, true);
        $lock = @fopen("$local/hermes-config.lock", 'c');
        if ($lock === false || !flock($lock, LOCK_EX)) {
            HermesConfigBackup::fail($local, 'config.yaml', null, 'cannot take the hermes-config lock');
            return;
        }
        try { // every step checks again under the lock: another start may have done it
            if (self::migrationDue($cfg)) {
                self::migrate($home, $hidden);
            }
            if (!is_file($cfg)) {
                HermesConfig::put($cfg, $seed); // throws: a start never runs on a half-written config
                HermesConfigBackup::log($local, 'seed', $cfg, null, null, $seed, null, 'first start');
            }
            if (!self::hasSkillDir($cfg, $skillDir) && self::bin() !== '') {
                list($ok, $dirs) = self::getList($home, 'skills.external_dirs');
                if (!$ok) {
                    HermesConfigBackup::fail($local, 'config.yaml', 'skills.external_dirs', "the Pikkumies skills are not loaded: could not read skills.external_dirs ($dirs)");
                } elseif (!in_array($skillDir, $dirs, true)) { // listed but written some other way: never add it twice
                    self::setList($home, 'skills.external_dirs', array_merge($dirs, [$skillDir]), 'repair-external-dirs');
                }
            }
            if (!HermesTelemetry::isOff($cfg, $offer) && self::bin() !== '') { // else the seed has it, or the next start does it
                HermesTelemetry::repair($home, $offer);
            }
            if (!is_file(self::skinMarker($local))) {
                self::offerSkin($home);
            }
            if (!is_file(self::browseMarker($local))) {
                self::offerBrowse($home);
            }
        } finally {
            flock($lock, LOCK_UN);
            fclose($lock);
        }
    }

    public static function skinMarker($local)
    {
        return "$local/state/hermes-skin.json";
    }

    /**
     * The Pikkumies skin in display.skin, once: only when the user's file names no skin (any `skin:` key, block or flow
     * YAML, counts as the user's choice and stays). Without a built Hermes it waits; the marker only when done, so a
     * later `/skin default` is never undone. Backed up and logged as skin-pikkumies.
     */
    public static function offerSkin($home)
    {
        $local = dirname($home);
        if (!preg_match('/(^|[\s{,])skin\s*:/m', (string) @file_get_contents("$home/config.yaml"))) {
            if (self::bin() === '' || !self::setValue($home, 'display.skin', StatusTheme::SKIN, 'skin-pikkumies', 'display.skin ' . StatusTheme::SKIN)) {
                return false;
            }
        }
        try {
            HermesConfig::put(self::skinMarker($local), json_encode(['skin' => StatusTheme::SKIN, 'at' => gmdate('c')]) . "\n");
        } catch (Exception $x) {
            return HermesConfigBackup::fail($local, 'state', null, $x->getMessage());
        }
        return true;
    }

    public static function browseMarker($local)
    {
        return "$local/state/hermes-browser.json";
    }

    /**
     * browser.restrict_evaluate true, once, for an install seeded before the browse unit (ADR-0077): only when the user's file
     * does not name the key (a value there is the user's and stays; the browser stays off while it is not true). Waits
     * for a built Hermes; the marker only when done. Backed up and logged as browser-restrict-evaluate.
     */
    public static function offerBrowse($home)
    {
        $local = dirname($home);
        if (!preg_match('/^\s+restrict_evaluate\s*:/m', (string) @file_get_contents("$home/config.yaml"))) {
            if (self::bin() === '' || !self::setValue($home, 'browser.restrict_evaluate', 'true', 'browser-restrict-evaluate', 'browser.restrict_evaluate true')) {
                return false;
            }
        }
        try {
            HermesConfig::put(self::browseMarker($local), json_encode(['restrict_evaluate' => true, 'at' => gmdate('c')]) . "\n");
        } catch (Exception $x) {
            return HermesConfigBackup::fail($local, 'state', null, $x->getMessage());
        }
        return true;
    }

    public static function marker($local)
    {
        return "$local/state/hermes-config.json";
    }

    /** True until the migration finished, and again when line 1 is the old header (an older version rewrote the file). */
    public static function migrationDue($cfg)
    {
        return !is_file(self::marker(dirname(dirname($cfg)))) || self::oldHeader($cfg);
    }

    /** Line 1 is the header every start used to write; its middle holds a HOME-dependent path, so prefix and suffix. */
    public static function oldHeader($cfg)
    {
        $f = @fopen($cfg, 'r');
        $line = $f ? rtrim((string) fgets($f, 4096), "\r\n") : '';
        if ($f) {
            fclose($f);
        }
        return strpos($line, self::OLD_HEAD) === 0 && substr($line, -strlen(self::OLD_TAIL)) === self::OLD_TAIL;
    }

    public static function hasSkillDir($cfg, $skillDir)
    {
        return strpos((string) @file_get_contents($cfg), $skillDir) !== false;
    }

    /** The one-time steps; the marker only when all of them are done. */
    public static function migrate($home, array $hidden)
    {
        $local = dirname($home);
        $ok = true;
        $cfg = "$home/config.yaml";
        if (is_file($cfg) && self::oldHeader($cfg)) {
            $bytes = (string) file_get_contents($cfg);
            $nl = strpos($bytes, "\n");
            $ok = HermesConfigBackup::write($local, $cfg, 'migrate-header', HermesConfig::seedHeader() . ($nl === false ? '' : substr($bytes, $nl + 1)), 'line 1 only') && $ok;
        }
        $env = "$home/.env";
        $bytes = is_file($env) ? (string) file_get_contents($env) : '';
        $kept = (string) preg_replace('/^PIKKUMIES_API_KEY=[^\n]*(\n|$)/m', '', $bytes);
        if ($kept !== $bytes) {
            $ok = HermesConfigBackup::write($local, $env, 'migrate-env-key', $kept, 'PIKKUMIES_API_KEY line only') && $ok;
        }
        $ok = self::dropHidden($home, $hidden) && $ok;
        try {
            if ($ok) {
                HermesConfig::put(self::marker($local), json_encode(['layout' => 2, 'migratedAt' => gmdate('c')]) . "\n");
            }
        } catch (Exception $x) {
            return HermesConfigBackup::fail($local, 'state', null, $x->getMessage());
        }
        return $ok;
    }

    /** Hidden shipped skills out of Hermes' skills.disabled; false when it has to wait for Hermes. */
    public static function dropHidden($home, array $hidden)
    {
        $bytes = (string) @file_get_contents("$home/config.yaml");
        $named = array_filter($hidden, function ($n) use ($bytes) {
            return strpos($bytes, (string) $n) !== false;
        });
        if (!$named || strpos($bytes, 'disabled:') === false) {
            return true; // nothing there to take out, no Hermes process
        }
        if (self::bin() === '') {
            return false;
        }
        list($ok, $list) = self::getList($home, 'skills.disabled');
        if (!$ok) {
            return HermesConfigBackup::fail(dirname($home), 'config.yaml', 'skills.disabled', "could not read skills.disabled ($list)");
        }
        $kept = array_values(array_filter($list, function ($n) use ($hidden) {
            return !in_array($n, $hidden, true);
        }));
        return count($kept) === count($list) || self::setList($home, 'skills.disabled', $kept, 'migrate-skills-disabled');
    }

    /** [true, list] from `hermes config get <key> --json`, which may print a list or a JSON string holding one; [false, why]. */
    public static function getList($home, $key)
    {
        $r = self::hermes($home, ['config', 'get', $key, '--json', '--raw']);
        $v = json_decode(trim($r['out']), true);
        if (is_string($v)) {
            $v = json_decode($v, true);
        }
        if ($r['code'] !== 0 || !is_array($v)) {
            return [false, 'exit ' . $r['code'] . ': ' . self::firstLine($r['err'] . "\n" . $r['out'])];
        }
        return [true, array_values($v)];
    }

    /** `hermes config set <key> <json list>`, through setValue(). */
    public static function setList($home, $key, array $list, $action)
    {
        return self::setValue($home, $key, json_encode(array_values($list), JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE), $action, count($list) . ' entries');
    }

    /** Back up config.yaml, then `hermes config set <key> <value>` (Hermes coerces the text); logged either way. */
    public static function setValue($home, $key, $value, $action, $detail)
    {
        $local = dirname($home);
        $cfg = "$home/config.yaml";
        $before = (string) @file_get_contents($cfg);
        $backup = HermesConfigBackup::copy($local, $cfg, $before);
        if ($backup === null) {
            return HermesConfigBackup::fail($local, 'config.yaml', $key, 'no backup could be written; nothing changed');
        }
        $r = self::hermes($home, ['config', 'set', $key, (string) $value]);
        clearstatcache();
        $after = @file_get_contents($cfg);
        if ($r['code'] !== 0) {
            return HermesConfigBackup::fail($local, 'config.yaml', $key, 'hermes config set exit ' . $r['code'] . ': ' . self::firstLine($r['err'] . "\n" . $r['out']), $backup);
        }
        HermesConfigBackup::log($local, $action, $cfg, $key, $before, $after === false ? null : $after, $backup, $detail);
        return true;
    }

    private static function firstLine($s)
    {
        $s = trim((string) $s);
        return substr($s === '' ? 'no output' : strtok($s, "\n"), 0, 200);
    }

    /** Hermes with the environment every Pikkumies start gives it; argv, never a shell string. */
    private static function hermes($home, array $args)
    {
        try {
            return ToolProc::run(array_merge([self::bin()], $args), HermesConfig::env($home));
        } catch (Exception $x) {
            return ['code' => 127, 'out' => '', 'err' => $x->getMessage()];
        }
    }

    private static function bin()
    {
        return self::$bin !== null ? self::$bin : HermesInstall::bin();
    }
}
