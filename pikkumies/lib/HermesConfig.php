<?php
/**
 * HermesConfig: generates Hermes' home (HERMES_HOME = local/hermes) from the tracked tree.
 *
 * - config.yaml: model provider, skills.external_dirs (core + enabled packs, lowest precedence,
 *   so local/agent-made skills in $HERMES_HOME/skills shadow shipped ones), shell hooks.
 * - .env: provider key (0600). SOUL.md: doctrine + enabled packs' doctrine fragments.
 * Regenerated on install and update; hand edits belong in local/config.php, not here.
 */
class HermesConfig
{
    public static function home()
    {
        return Config::localDir() . '/hermes';
    }

    public static function write(array $config, array $enabledPacks)
    {
        $home = self::home();
        @mkdir($home . '/skills', 0700, true);
        $prov = Provider::resolve($config);

        file_put_contents($home . '/config.yaml', self::renderYaml($prov, self::skillDirs($enabledPacks), self::hookEntries($enabledPacks)));
        $env = $home . '/.env';
        // Key lives only in .env (0600); config.yaml points at it via model.key_env.
        file_put_contents($env, "PIKKUMIES_API_KEY=" . $prov['key'] . "\n");
        chmod($env, 0600);
        file_put_contents($home . '/SOUL.md', self::renderSoul($enabledPacks));
        return $home;
    }

    public static function skillDirs(array $enabledPacks)
    {
        $dirs = [Config::root() . '/skills'];
        foreach ($enabledPacks as $name) {
            $d = Packs::dir() . '/' . $name . '/skills';
            if (is_dir($d)) {
                $dirs[] = $d;
            }
        }
        return $dirs;
    }

    /** Shell hooks: hooks/<event>/<name>.php in core and enabled packs, run with php. */
    public static function hookEntries(array $enabledPacks)
    {
        $roots = [Config::root() . '/hooks'];
        foreach ($enabledPacks as $name) {
            $roots[] = Packs::dir() . '/' . $name . '/hooks';
        }
        $entries = [];
        foreach ($roots as $root) {
            foreach ((array) glob($root . '/*/*.php') as $script) {
                $entries[basename(dirname($script))][] = $script;
            }
        }
        ksort($entries);
        return $entries;
    }

    public static function renderYaml(array $prov, array $skillDirs, array $hooks)
    {
        $y = "# Generated by pikkumies. Edit local/config.php instead; this file is rewritten.\n";
        // Shape per Hermes docs (integrations/providers.md: provider custom + base_url + key_env).
        $y .= "model:\n  provider: custom\n  base_url: " . self::q($prov['endpoint']) . "\n  default: " . self::q($prov['model']) . "\n  key_env: PIKKUMIES_API_KEY\n";
        $y .= "skills:\n  external_dirs:\n";
        foreach ($skillDirs as $d) {
            $y .= "    - " . self::q($d) . "\n";
        }
        if ($hooks) {
            $y .= "hooks:\n";
            foreach ($hooks as $event => $scripts) {
                $y .= "  " . $event . ":\n";
                foreach ($scripts as $s) {
                    $y .= "    - command: " . self::q(PHP_BINARY . ' ' . $s) . "\n      timeout: 10\n";
                    if ($event === 'pre_tool_call') {
                        $y .= "      fail_closed: false\n";
                    }
                }
            }
        }
        return $y;
    }

    public static function renderSoul(array $enabledPacks)
    {
        $parts = [];
        foreach (['soul', 'voice', 'doctrine', 'safety'] as $f) {
            $p = Config::root() . '/doctrine/' . $f . '.md';
            if (is_file($p)) {
                $parts[] = trim((string) file_get_contents($p));
            }
        }
        foreach ($enabledPacks as $name) {
            $p = Packs::dir() . '/' . $name . '/doctrine.md';
            if (is_file($p)) {
                $parts[] = trim((string) file_get_contents($p));
            }
        }
        return implode("\n\n---\n\n", $parts) . "\n";
    }

    /** YAML double-quoted scalar. */
    public static function q($s)
    {
        return '"' . str_replace(['\\', '"'], ['\\\\', '\\"'], (string) $s) . '"';
    }
}
