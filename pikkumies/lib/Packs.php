<?php
/**
 * Packs: bundles under ../packs/<name>/ described by pack.json ({"name","description"}).
 *
 * Every pack is always loaded (ADR-0006): Hermes shows the model only a short index of
 * skills and loads a skill's text when it is used, so shipping all of them costs little.
 * A pack is left out only when listed in config packs.disabled; the root pack is also left
 * out when root.disabled is set. Anything every machine needs belongs in the core runtime.
 */
class Packs
{
    public static function dir()
    {
        return dirname(Config::root()) . '/packs';
    }

    public static function all()
    {
        $packs = [];
        foreach ((array) glob(self::dir() . '/*/pack.json') as $file) {
            $meta = json_decode((string) file_get_contents($file), true);
            if (is_array($meta) && isset($meta['name'])) {
                $meta['path'] = dirname($file);
                $packs[$meta['name']] = $meta;
            }
        }
        ksort($packs);
        return $packs;
    }

    /** Names of loaded packs: all of them minus packs.disabled (and root when root.disabled). */
    public static function enabled(array $config)
    {
        $off = isset($config['packs']['disabled']) ? (array) $config['packs']['disabled'] : [];
        if (!empty($config['root']['disabled'])) {
            $off[] = 'root';
        }
        return array_values(array_diff(array_keys(self::all()), $off));
    }

    /** INDEX.md is generated from pack.json files; never edit it by hand. */
    public static function renderIndex()
    {
        $out = "# Packs index\n\nGenerated by `pikkumies packs index` from each pack.json. Do not edit by hand.\n\n| Pack | Description |\n|---|---|\n";
        foreach (self::all() as $name => $meta) {
            $out .= '| [' . $name . '](' . $name . '/README.md) | ' . (isset($meta['description']) ? $meta['description'] : '') . " |\n";
        }
        return $out;
    }
}
