<?php
/**
 * Packs: bundles under ../packs/<name>/ described by pack.json.
 *
 * pack.json: {"name","description","detect":{"pmss":true|"root":true|"apps":[...]|"always":true}}
 * Enabling a pack never downloads anything: git already shipped it. Enabled = listed in
 * config packs.enabled, or matched by detect rules when packs.auto is true.
 */
class Packs
{
    public static function dir()
    {
        return dirname(Config::root()) . '/packs';
    }

    public static function all()
    {
        $packs = [];
        foreach ((array) glob(self::dir() . '/*/pack.json') as $file) {
            $meta = json_decode((string) file_get_contents($file), true);
            if (is_array($meta) && isset($meta['name'])) {
                $meta['path'] = dirname($file);
                $packs[$meta['name']] = $meta;
            }
        }
        ksort($packs);
        return $packs;
    }

    public static function matches(array $detect, array $profile, array $config)
    {
        if (!empty($detect['always'])) {
            return true;
        }
        if (!empty($detect['pmss']) && !empty($profile['pmss'])) {
            return true;
        }
        if (!empty($detect['root']) && !empty($profile['root']['available']) && empty($config['root']['disabled'])) {
            return true;
        }
        if (!empty($detect['apps']) && array_intersect($detect['apps'], $profile['apps'])) {
            return true;
        }
        return false;
    }

    /** Names of enabled packs: explicit list plus (when auto) detected ones. */
    public static function enabled(array $profile, array $config)
    {
        $names = $config['packs']['enabled'];
        if (!empty($config['packs']['auto'])) {
            foreach (self::all() as $name => $meta) {
                if (isset($meta['detect']) && self::matches($meta['detect'], $profile, $config)) {
                    $names[] = $name;
                }
            }
        }
        $names = array_values(array_unique($names));
        sort($names);
        return $names;
    }

    /** INDEX.md is generated from pack.json files; never edit it by hand. */
    public static function renderIndex()
    {
        $out = "# Packs index\n\nGenerated by `pikkumies packs index` from each pack.json. Do not edit by hand.\n\n| Pack | Enabled when | Description |\n|---|---|---|\n";
        foreach (self::all() as $name => $meta) {
            $when = [];
            foreach ((array) (isset($meta['detect']) ? $meta['detect'] : []) as $k => $v) {
                $when[] = $k . (is_array($v) ? ': ' . implode(', ', $v) : '');
            }
            $out .= '| [' . $name . '](' . $name . '/README.md) | ' . implode('; ', $when) . ' | ' . (isset($meta['description']) ? $meta['description'] : '') . " |\n";
        }
        return $out;
    }
}
