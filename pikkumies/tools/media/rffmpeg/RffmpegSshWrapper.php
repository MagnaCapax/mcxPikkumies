<?php
/**
 * RffmpegSshWrapper: the generated PHP file installed as rffmpeg's `commands.ssh` (Review fixes 2,
 * CWE-295/CWE-863). Upstream's own `generate_ssh_command` (rffmpeg.upstream:254-287) always sends
 * `-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null` with no `-F /dev/null`, before
 * `remote.args` -- and ssh keeps the FIRST value given for a repeated option, so rffmpeg's own
 * insecure defaults cannot be overridden from `remote.args` alone. This wrapper becomes the actual
 * ssh(1) rffmpeg execs: it reads this unit's own state.json for the one recorded host's nick, calls
 * Services::refuseListed($host) on every single connection (not just at add-host time, ADR-0068), and
 * PREPENDS the real pinned-host-key options before forwarding everything upstream passed it (which
 * still contains upstream's own insecure `-o` pair later in the argv -- harmless, since ssh keeps the
 * first value). Fails closed: no recorded host, no Services list, or a denied/unpinned host all
 * refuse to connect rather than silently falling back to upstream's behaviour.
 */
class RffmpegSshWrapper
{
    /** The generated file's PHP source; written by RffmpegVenv::install(), never edited by hand. */
    public static function content($servicesPath, $stateFile, $sshBin)
    {
        $esc = function ($s) {
            return var_export((string) $s, true);
        };
        return "#!/usr/bin/env php\n<?php\n"
            . "/* Generated by pikkumies/tools/media/rffmpeg (RffmpegSshWrapper); do not edit, add-host/install regenerate this file. */\n"
            . 'define(\'RFFMPEG_WRAPPER_SERVICES\', ' . $esc($servicesPath) . ");\n"
            . 'define(\'RFFMPEG_WRAPPER_STATE\', ' . $esc($stateFile) . ");\n"
            . 'define(\'RFFMPEG_WRAPPER_SSH\', ' . $esc($sshBin) . ");\n"
            . <<<'PHP'
$state = is_file(RFFMPEG_WRAPPER_STATE) ? json_decode((string) @file_get_contents(RFFMPEG_WRAPPER_STATE), true) : null;
$hosts = is_array($state) && isset($state['hosts']) && is_array($state['hosts']) ? $state['hosts'] : [];
$nick = $hosts ? array_keys($hosts)[0] : null;
if ($nick === null) {
    fwrite(STDERR, "rffmpeg ssh wrapper: no GPU host recorded in state.json; refusing to connect\n");
    exit(1);
}
if (!is_file(RFFMPEG_WRAPPER_SERVICES)) {
    fwrite(STDERR, "rffmpeg ssh wrapper: the Services list is not installed; refusing to connect\n");
    exit(1);
}
require_once RFFMPEG_WRAPPER_SERVICES;
$args = array_slice($argv, 1);
$host = null;
foreach (array_reverse($args) as $a) {
    if (is_string($a) && strpos($a, '@') !== false) {
        $host = substr($a, strrpos($a, '@') + 1);
        break;
    }
}
if ($host === null || $host === '') {
    fwrite(STDERR, "rffmpeg ssh wrapper: no user@host argument found; refusing to connect\n");
    exit(1);
}
try {
    Services::refuseListed($host);
    $knownHosts = Services::secretDir($nick) . '/known_hosts';
} catch (Throwable $e) {
    fwrite(STDERR, 'rffmpeg ssh wrapper: ' . $e->getMessage() . "\n");
    exit(1);
}
// Prepended FIRST: ssh keeps the first value of a repeated -o option, so these win over upstream's
// own (later) -o StrictHostKeyChecking=no / UserKnownHostsFile=/dev/null pair.
$prefix = ['-F', '/dev/null', '-o', 'UserKnownHostsFile=' . $knownHosts, '-o', 'GlobalKnownHostsFile=/dev/null',
    '-o', 'StrictHostKeyChecking=yes', '-o', 'IdentitiesOnly=yes', '-o', 'BatchMode=yes'];
$full = array_merge([RFFMPEG_WRAPPER_SSH], $prefix, $args);
$cmd = 'exec';
foreach ($full as $w) {
    $cmd .= ' ' . escapeshellarg((string) $w);
}
$p = proc_open($cmd, [0 => STDIN, 1 => STDOUT, 2 => STDERR], $pipes);
exit($p === false ? 1 : proc_close($p));

PHP;
    }
}
