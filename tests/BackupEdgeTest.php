    'backup: restore() keeps a partially-written new target directory when the tool\'s restore() throws after creating one file' => function () {
        // Defect-check: this directly exercises the "never accept data loss when recovery is possible" guard --
        // @rmdir() only removes an EMPTY directory, so a target holding the partial write below must survive.
        $home = testTempDir('pk-backup-edge-restore');
        try {
            testWithEnv(array('HOME' => $home), function () use ($home) {
                $target = "$home/restore-edge-1";
                $ctx = array('mountinfo' => '/dev/null');
                $method = new ReflectionMethod('Backup', 'restore');
                $method->setAccessible(true);
                try {
                    $method->invoke(null, new BackupEdgeRestoreTool(), array('snapA'), array('target' => $target), $ctx);
                    check(false, 'the stub tool\'s restore() should have thrown');
                } catch (CliError $e) {
                    check(strpos($e->getMessage(), 'failed partway through') !== false, 'propagated error: ' . $e->getMessage());
                }
                check(is_dir($target) && is_file("$target/partial.txt"), 'the partially-written target directory was removed on failure');
            });
        } finally {
            testRmTree($home);
        }
    },
    'backup store: prompt() refuses immediately when stdin is not a TTY, with no script(1)/pty dependency' => function () {
        $dir = testTempDir('pk-backup-edge-prompt');
