            file_put_contents($runner, '<?php
require ' . var_export(dirname(__DIR__) . '/pikkumies/tools/backup/lib/BackupStore.php', true) . ';
require ' . var_export(dirname(__DIR__) . '/pikkumies/lib/Cli.php', true) . ';
try {
