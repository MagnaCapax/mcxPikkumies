            $out = trim(stream_get_contents($pipes[1]));
            fclose($pipes[1]);
            proc_close($p);
            check(strpos($out, 'THROWN:') === 0 && strpos($out, 'not one; nothing stored') !== false, 'stdin-from-/dev/null prompt(): ' . $out);
        } finally {
            testRmTree($dir);
        }
