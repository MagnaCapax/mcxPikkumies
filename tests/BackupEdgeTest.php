            }
        }
        $ok1 = BackupRules::keep(array('keep-daily' => '1'));
        check($ok1 === array('keep-daily' => '1'), 'a valid count should be accepted: ' . json_encode($ok1));
        $ok2 = BackupRules::keep(array('keep-within' => '7d'));
        check($ok2 === array('keep-within' => '7d'), 'a valid keep-within should be accepted: ' . json_encode($ok2));
    },
    'backup rules: checked() states the exact "did not finish" note when the exit code means neither success nor confirmed damage' => function () {
        $rec = BackupRules::checked(false, false, array('code' => 1, 'out' => 'x', 'err' => 'y'), false);
        check($rec['note'] === 'the check did not finish (lock, network, login or option: see output), so it says nothing about damage',
