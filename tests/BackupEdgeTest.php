    'borg repo: item() detects a hard link from the \'source\' field alone, and separately from a mode starting with \'h\' alone' => function () {
        $withSource = BorgRepo::item(array('type' => '-', 'path' => 'a/b.txt', 'size' => 5,
            'mtime' => '2026-10-01T02:00:00.000000', 'source' => 'a/orig.txt', 'mode' => '-rw-r--r--'));
        check(!empty($withSource['hardlink']) && $withSource['bytes'] === null && $withSource['link_to'] === '/a/orig.txt',
            'source-field hardlink: ' . json_encode($withSource));
        $withHMode = BorgRepo::item(array('type' => '-', 'path' => 'a/c.txt', 'mode' => 'hrw-r--r--'));
        check(!empty($withHMode['hardlink']) && $withHMode['bytes'] === null && $withHMode['link_to'] === null,
            'h-mode hardlink (no source field at all): ' . json_encode($withHMode));
        // Contrast: a plain file (no source, mode not starting with h) is never flagged as a hardlink.
        $plain = BorgRepo::item(array('type' => '-', 'path' => 'a/d.txt', 'size' => 9, 'mode' => '-rw-r--r--'));
        check(empty($plain['hardlink']) && $plain['bytes'] === 9, 'a plain file was wrongly flagged as a hardlink: ' . json_encode($plain));
    },
    'borg repo: stored() refuses a path starting with \'-\' before any borg argv is built' => function () {
