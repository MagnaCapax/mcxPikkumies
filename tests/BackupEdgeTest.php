return array(
    'borg prune: wouldPrune() parses a literal, hand-typed "Would prune:"/"Keeping" stderr block into exact records' => function () {
        // Independent fixture: this stderr block is hand-typed here, not generated by the project's own fake-borg
        // stderr generator -- a shared misunderstanding could otherwise hide in both.
        $id = str_repeat('a', 64);
        $stderr = "Keeping archive (rule: daily #1):            box-3   Thu, 2026-10-03 03:00:00 [" . str_repeat('c', 64) . "]\n"
            . "Keeping archive (rule: weekly #1):            box-2   Wed, 2026-10-02 03:00:00 [" . str_repeat('b', 64) . "]\n"
            . "Would prune:                                  box-1   Tue, 2026-10-01 03:00:00 [$id]\n";
        $r = BorgPrune::wouldPrune($stderr);
        // Literal, independently computed: (new DateTime('2026-10-01 03:00:00', new DateTimeZone('UTC')))->getTimestamp().
        check($r['keep'] === 2, 'keep count: ' . json_encode($r));
        check(count($r['remove']) === 1 && $r['remove'][0]['id'] === 'box-1' && $r['remove'][0]['snapshot_id'] === $id
            && $r['remove'][0]['time'] === 1790823600, 'the single removal record: ' . json_encode($r));
    },
    'restic prune: keepFlags() converts keep-within H to lowercase h and leaves d/m/y unchanged' => function () {
        // restic has no native hour-abbreviation case either way; this pins the one conversion the unit performs.
        check(ResticPrune::keepFlags(array('keep-within' => '5H')) === array('--keep-within', '5h'), 'H case');
        check(ResticPrune::keepFlags(array('keep-within' => '3d')) === array('--keep-within', '3d'), 'd case passthrough');
        check(ResticPrune::keepFlags(array('keep-within' => '3m')) === array('--keep-within', '3m'), 'm case passthrough');
        check(ResticPrune::keepFlags(array('keep-within' => '3y')) === array('--keep-within', '3y'), 'y case passthrough');
    },
    'backup rules: newestFirst() keeps reverse-input order among snapshots with identical times' => function () {
        $snap = function ($id) {
            return array('time' => '1000', 'paths' => array('/x'), 'id' => $id);
        };
        $all = array($snap('a'), $snap('b'), $snap('c'));
        $r = BackupRules::newestFirst($all, null);
        check(array_column($r, 'id') === array('c', 'b', 'a'), 'tie-break order: ' . json_encode(array_column($r, 'id')));
    },
    'restic repo: time() converts an RFC3339 timestamp to the same unix second regardless of fractional-digit count or an explicit offset' => function () {
        // Literal, independently computed: strtotime('2026-10-01T03:00:00+03:00').
        $want = 1790812800;
        check(ResticRepo::time('2026-10-01T03:00:00.123456789+03:00') === $want, 'with nanoseconds: ' . ResticRepo::time('2026-10-01T03:00:00.123456789+03:00'));
        check(ResticRepo::time('2026-10-01T03:00:00+03:00') === $want, 'without fractional digits: ' . ResticRepo::time('2026-10-01T03:00:00+03:00'));
    },
    'backup store: commit() with the identical password already stored writes no .prev-<time> file' => function () {
        $secretDir = testTempDir('pk-backup-edge-secret');
        $localDir = testTempDir('pk-backup-edge-local');
        try {
            $store = new BackupStore('resticedge', $secretDir, $localDir);
            $store->stage('sftp:me@box:repo', 'same-password-value');
            $kept1 = $store->commit();
            check($kept1 === null, 'the very first login should keep nothing: ' . json_encode($kept1));
            $store->stage('sftp:me@box:repo', 'same-password-value');
            $kept2 = $store->commit();
            check($kept2 === null, 'an identical re-login created a .prev file it should not have: ' . json_encode($kept2));
            check(!glob("$secretDir/resticedge.prev-*"), 'a .prev file exists despite an identical password');
            // Contrast: a genuinely DIFFERENT password must be kept, proving the identical-password path above
            // is not simply "commit() never keeps anything".
            $store->stage('sftp:me@box:repo', 'a-different-password-value');
            $kept3 = $store->commit();
            check($kept3 !== null && is_file($kept3), 'a changed password should have kept the old one: ' . json_encode($kept3));
        } finally {
            testRmTree($secretDir);
            testRmTree($localDir);
        }
    },
    'backup rules: idle() never treats this process\'s own pid as a conflicting backup job' => function () {
        $procRoot = testTempDir('pk-backup-edge-proc');
        try {
            $uid = function_exists('posix_geteuid') ? posix_geteuid() : getmyuid();
            $own = getmypid();
            mkdir("$procRoot/$own", 0700, true);
            file_put_contents("$procRoot/$own/comm", "restic\n");
            BackupRules::idle(array('procRoot' => $procRoot, 'uid' => $uid)); // must NOT throw
            // Contrast: a DIFFERENT fake pid, same uid, same comm, DOES conflict -- proving idle() is not simply a no-op.
            $other = $own + 123;
            mkdir("$procRoot/$other", 0700, true);
            file_put_contents("$procRoot/$other/comm", "restic\n");
            try {
                BackupRules::idle(array('procRoot' => $procRoot, 'uid' => $uid));
                check(false, 'a different pid running restic should have refused');
            } catch (CliError $e) {
                check(strpos($e->getMessage(), 'already running') !== false, 'message: ' . $e->getMessage());
            }
        } finally {
            testRmTree($procRoot);
        }
    },
    'backup rules: keep() rejects 0/negative counts and a keep-within value with no unit suffix' => function () {
