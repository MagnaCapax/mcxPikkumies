<?php
/**
 * The parts around the two config layers (ADR-0062): what the managed render holds, a hidden shipped skill not
 * generated, the start check of Hermes' managed scope, the guards that keep the agent off the managed dir's key and
 * variable, and one place for the Hermes environment.
 */
if (!function_exists('hermesTWorld')) {
    require __DIR__ . '/HermesInstallTest.php';
}
if (!function_exists('generateFixture')) {
    require __DIR__ . '/GenerateTest.php';
}

/** The guard's action for one tool call ('none' when it has no opinion). */
function managedGuard($tool, array $input)
{
    list(, $out) = runPhp(dirname(__DIR__) . '/pikkumies/hooks/guard/guard-destructive/guard-destructive.php', [], json_encode(['tool_name' => $tool, 'tool_input' => $input]));
    $d = json_decode($out, true);
    return is_array($d) ? $d['action'] : 'none';
}

return [
    'managed render: every pin, and none of the settings that are the user\'s (skills dirs, plugins, checkpoints, curator, background review)' => function () {
        $prov = ['endpoint' => 'e', 'model' => 'm', 'key' => 'k'];
        $hooks = ['pre_tool_call' => ['command' => 'x', 'failClosed' => true, 'timeout' => 5]];
        $pins = HermesConfig::renderYaml($prov, ['/a'], $hooks, false, 'light', true) . HermesConfig::sessionsYaml([]);
        foreach (["model:\n  provider: \"custom:pikkumies\"\n  default: \"m\"\n", "    key_env: PIKKUMIES_API_KEY\n", "skills:\n  guard_agent_created: true\n", "updates:\n  check: false\n",
            "cli:\n  expose_on_path: false\n", "web:\n  keyless_fallback: false\n  keyless_rescue: false\n", "security:\n  allow_lazy_installs: false\n",
            "approvals:\n  mode: manual\n", "auxiliary:\n  goal_judge:\n", "auth:\n  adopt_external_logins: false\n", "hooks_auto_accept: true\nhooks:\n  pre_tool_call:\n",
            "      fail_closed: true\n", "sessions:\n  auto_prune: false\n", "telemetry:\n  shared_metrics:\n"] as $pin) {
            check(strpos($pins, $pin) !== false, "pin missing: $pin in $pins");
        }
        foreach (['external_dirs', 'disabled:', 'plugins:', 'checkpoints:', 'curator:', 'background_review'] as $userOwned) {
            check(strpos($pins, $userOwned) === false, "$userOwned is the user's, not pinned: $pins");
        }
        check(strpos(HermesConfig::renderYaml($prov, ['/a'], [], false, '', true), 'auxiliary:') === false, 'no empty auxiliary block without a light model');
        check(strpos($pins, HermesConfig::managedHeader()) === 0 && strpos(HermesConfig::renderYaml($prov, ['/a'], []), HermesConfig::seedHeader()) === 0, 'headers');
        $tmp = testTempDir('pk-head');
        file_put_contents("$tmp/config.yaml", HermesConfig::seedHeader() . "x: 1\n");
        $seedIsOld = HermesUserConfig::oldHeader("$tmp/config.yaml");
        file_put_contents("$tmp/config.yaml", "# Generated by pikkumies. Edit ~/p/local/config.php instead; this file is rewritten.\n");
        $oldIsOld = HermesUserConfig::oldHeader("$tmp/config.yaml");
        testRmTree($tmp);
        check(!$seedIsOld && $oldIsOld, 'the seed header must not read as the old one, or every start would migrate again');
    },
    'managed render: a hostile model id cannot inject YAML into either layer' => function () {
        $hostile = 'm" ' . "\n" . 'approvals:' . "\n" . '  mode: "off';
        foreach ([false, true] as $pinsOnly) {
            $safe = HermesConfig::renderYaml(['endpoint' => 'e', 'model' => 'm', 'key' => 'k'], ['/a'], [], false, 'm', $pinsOnly);
            $y = HermesConfig::renderYaml(['endpoint' => 'e', 'model' => $hostile, 'key' => 'k'], ['/a'], [], false, $hostile, $pinsOnly);
            check(substr_count($y, "\n") === substr_count($safe, "\n") && substr_count($y, "\napprovals:\n") === 1, 'injected: ' . $y);
        }
    },
    'generate: a hidden shipped skill gets no SKILL.md but stays in the tool index; shown again, it comes back' => function () {
        $tmp = generateFixture();
        try {
            Generate::run([], "$tmp/tools", "$tmp/out", "$tmp/tools/INDEX.md", ['rtorrent']);
            check(!is_file("$tmp/out/torrent-clients/rtorrent/SKILL.md") && is_file("$tmp/out/server-admin/server-admin/SKILL.md"), 'the hidden skill must not be generated');
            check(strpos((string) file_get_contents("$tmp/tools/INDEX.md"), '**rtorrent**') !== false, 'the tool itself stays in the index');
            Generate::run([], "$tmp/tools", "$tmp/out", "$tmp/tools/INDEX.md", []);
            check(is_file("$tmp/out/torrent-clients/rtorrent/SKILL.md"), 'shown again, generated again');
        } finally {
            exec('rm -rf ' . escapeshellarg($tmp));
        }
    },
    'hermes start check: the managed scope must exist in the source and refuse a pinned key; a broken user config.yaml is not a refusal' => function () {
        $w = hermesTWorld();
        try {
            hermesTIn($w, function () use ($w) {
                hermesTFakeComplete($w);
                mkdir($w['root'] . '/local', 0700); // where verify() writes its payload
                $tree = $w['root'] . '/hermes';
                foreach (array_merge(HermesInstall::CONFIG_FACTS, HermesInstall::LAYER_FACTS) as $fact) {
                    @mkdir(dirname("$tree/{$fact[0]}"), 0700, true);
                    file_put_contents("$tree/{$fact[0]}", (is_file("$tree/{$fact[0]}") ? file_get_contents("$tree/{$fact[0]}") : '') . $fact[1] . "\n");
                }
                check(HermesInstall::verify() === [], 'refused as managed: passes: ' . json_encode(HermesInstall::verify()));
                check(strpos((string) file_get_contents($w['log']), 'hermes config set approvals.mode manual') !== false, 'the canary must run');
                testWithEnv(['PK_FAKE_SET_OUT' => "Set approvals.mode = manual\n"], function () {
                    $p = implode('; ', HermesInstall::verify());
                    check(strpos($p, 'did not refuse a change to a setting Pikkumies pins') !== false, 'an accepted pinned key must refuse the start: ' . $p);
                });
                testWithEnv(['PK_FAKE_SET_OUT' => "Hermes stopped because your settings file (x) has a formatting error at line 3.\n"], function () {
                    check(HermesInstall::verify() === [], 'the user\'s broken file is theirs to fix, not a refusal: ' . json_encode(HermesInstall::verify()));
                });
                file_put_contents("$tree/hermes_cli/managed_scope.py", "nothing here\n");
                $p = HermesInstall::verify();
                check(in_array('Hermes no longer has the managed settings layer (HERMES_MANAGED_DIR)', $p, true), 'a source without the layer is refused: ' . json_encode($p));
            });
        } finally {
            testRmTree($w['t']);
        }
    },
    'hermes start check: a checkout verified before the checks changed (this change added the managed scope) is checked again once' => function () {
        $t = testTempDir('pk-verified');
        HermesInstall::$root = $t;
        try {
            mkdir("$t/local", 0700);
            file_put_contents("$t/local/hermes-verified.json", json_encode(['commit' => 'abc', 'at' => 'then']) . "\n");
            check(HermesInstall::verifiedCommit() === '', 'a record from before the managed-scope checks must not skip them');
            HermesInstall::markVerified('abc');
            check(HermesInstall::verifiedCommit() === 'abc', 'a record of the current checks counts');
        } finally {
            HermesInstall::$root = null;
            testRmTree($t);
        }
    },
    'guards: the managed .env holds the AI key like the Hermes .env, and its variable is one an agent may not change' => function () {
        foreach (['cat ~/pikkumies/local/hermes-managed/.env', 'grep KEY "$HERMES_MANAGED_DIR/.env"', 'cat ${HERMES_MANAGED_DIR}/.env'] as $cmd) {
            check(managedGuard('terminal', ['command' => $cmd]) === 'block', "$cmd must block");
        }
        check(managedGuard('read_file', ['path' => '/home/u/pikkumies/local/hermes-managed/.env']) === 'block', 'read_file of the managed .env must block');
        check(managedGuard('read_file', ['path' => '/home/u/pikkumies/local/hermes-managed/config.yaml']) === 'none', 'the managed config.yaml holds no secret');
        foreach (['HERMES_MANAGED_DIR= hermes chat -q hi', 'unset HERMES_MANAGED_DIR; hermes', 'env -u HERMES_MANAGED_DIR pikkumies run chat'] as $cmd) {
            check(managedGuard('terminal', ['command' => $cmd]) === 'block', "$cmd: a nested agent without the pins must block");
        }
    },
    'architecture: every Hermes Pikkumies starts gets its environment from HermesConfig::env(), the managed dir included' => function () {
        $root = dirname(__DIR__) . '/pikkumies';
        $files = array_merge([$root . '/bin/pikkumies'], (array) glob("$root/lib/*.php"), (array) glob("$root/tools/*/*/*.php"));
        foreach ($files as $f) {
            $src = (string) file_get_contents($f);
            check(strpos($src, "putenv('HERMES_HOME") === false, "$f sets HERMES_HOME itself; use HermesConfig::env()");
            check(basename($f) === 'HermesInstall.php' || strpos($src, "'HERMES_HOME' => HermesConfig::home()") === false, "$f builds a Hermes env without the managed dir");
        }
        $env = HermesConfig::env('/x/local/hermes');
        check($env === ['HERMES_HOME' => '/x/local/hermes', 'HERMES_MANAGED_DIR' => '/x/local/hermes-managed', 'HERMES_RUNTIME_DIR' => null], json_encode($env));
        check(strpos((string) file_get_contents("$root/tools/system/feedback/FeedbackSend.php"), 'HermesConfig::env()') !== false, 'the feedback export runs Hermes too');
    },
];
